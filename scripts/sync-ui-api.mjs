import { readFileSync, writeFileSync } from 'node:fs';
import { COMPONENT_REGISTRY, UI_EXPORT_NAMES } from '../src/library/docs/registry.js';

const start = '<!-- BEGIN GENERATED INVENTORY -->';
const end = '<!-- END GENERATED INVENTORY -->';
const registry = [...COMPONENT_REGISTRY].sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name));
const publicCount = registry.filter(({ publicExports }) => publicExports.length).length;
const names = (exports) => exports.map((name) => '`' + name + '`').join(', ');
const registryExports = new Set(registry.flatMap(({ publicExports }) => publicExports));
const cell = (value) => value.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim();
const inventory = [
  start,
  `The registry has **${registry.length} entries**. **${publicCount}** have supported imports from ` + '`@sankofa/ui`' + '.',
  '',
  '| Registry entry | Category | Package API or internal status |',
  '| --- | --- | --- |',
  ...registry.map((entry) => `| ${cell(entry.name)} | ${cell(entry.category)} | ${names(entry.publicExports) || cell(entry.internalReason)} |`),
  '',
  'Additional package exports include ' + names(UI_EXPORT_NAMES.filter((name) => !registryExports.has(name))) + '.',
  '',
  end,
].join('\n');

const readme = new URL('../README.md', import.meta.url);
const current = readFileSync(readme, 'utf8');
const first = current.indexOf(start);
const last = current.indexOf(end);
if (first === -1 || last < first) throw new Error('README inventory markers are missing or out of order.');

const entry = [
  '// Generated by npm run ui:sync. Edit the registry to change the package API.',
  'export {',
  ...UI_EXPORT_NAMES.map((name) => `  ${name},`),
  "} from '../../src/library/index.js';",
  '',
].join('\n');

const outputs = [
  [readme, current.slice(0, first) + inventory + current.slice(last + end.length)],
  [new URL('../packages/ui/index.js', import.meta.url), entry],
];
for (const [file, expected] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== expected.replaceAll('\r\n', '\n')) {
      throw new Error(`${file.pathname} is out of date. Run npm run ui:sync.`);
    }
  } else {
    writeFileSync(file, expected);
  }
}
